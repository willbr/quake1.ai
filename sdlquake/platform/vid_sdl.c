static int gpu_init(SDL_Window *win) {
    SDL_GPUShaderFormat fmts = SDL_GPU_SHADERFORMAT_SPIRV | SDL_GPU_SHADERFORMAT_MSL;
    gpu_device = SDL_CreateGPUDevice(fmts, false, NULL);
    if (!gpu_device) {
        Sys_Error("SDL_CreateGPUDevice failed: %s", SDL_GetError());
        return 0;
    }
    if (!SDL_ClaimWindowForGPUDevice(gpu_device, win)) {
        Sys_Error("SDL_ClaimWindowForGPUDevice failed: %s", SDL_GetError());
        return 0;
    }
    gpu_swapchain_format = SDL_GetGPUSwapchainTextureFormat(gpu_device, win);

    SDL_GPUShaderFormat active = SDL_GetGPUShaderFormats(gpu_device);

    SDL_GPUShaderCreateInfo vs_info = {0};
    SDL_GPUShaderCreateInfo fs_info = {0};
    vs_info.stage = SDL_GPU_SHADERSTAGE_VERTEX;
    fs_info.stage = SDL_GPU_SHADERSTAGE_FRAGMENT;
    fs_info.num_samplers         = 3;
    fs_info.num_uniform_buffers  = 1;   // scanline params

    if (active & SDL_GPU_SHADERFORMAT_MSL) {
        vs_info.code        = (const Uint8 *)palette_vert_msl;
        vs_info.code_size   = strlen(palette_vert_msl);
        vs_info.entrypoint  = "main0";
        vs_info.format      = SDL_GPU_SHADERFORMAT_MSL;
        fs_info.code        = (const Uint8 *)palette_frag_msl;
        fs_info.code_size   = strlen(palette_frag_msl);
        fs_info.entrypoint  = "main0";
        fs_info.format      = SDL_GPU_SHADERFORMAT_MSL;
    } else {
        vs_info.code        = palette_vert_spv;
        vs_info.code_size   = palette_vert_spv_size;
        vs_info.entrypoint  = "main";
        vs_info.format      = SDL_GPU_SHADERFORMAT_SPIRV;
        fs_info.code        = palette_frag_spv;
        fs_info.code_size   = palette_frag_spv_size;
        fs_info.entrypoint  = "main";
        fs_info.format      = SDL_GPU_SHADERFORMAT_SPIRV;
    }
    SDL_GPUShader *vs = SDL_CreateGPUShader(gpu_device, &vs_info);
    SDL_GPUShader *fs = SDL_CreateGPUShader(gpu_device, &fs_info);
    if (!vs || !fs) {
        Sys_Error("SDL_CreateGPUShader failed: %s", SDL_GetError());
        return 0;
    }

    SDL_GPUColorTargetDescription color_target = {0};
    color_target.format = gpu_swapchain_format;
    SDL_GPUGraphicsPipelineCreateInfo pipe_info = {0};
    pipe_info.vertex_shader   = vs;
    pipe_info.fragment_shader = fs;
    pipe_info.primitive_type  = SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
    pipe_info.rasterizer_state.fill_mode   = SDL_GPU_FILLMODE_FILL;
    pipe_info.rasterizer_state.cull_mode   = SDL_GPU_CULLMODE_NONE;
    pipe_info.rasterizer_state.front_face  = SDL_GPU_FRONTFACE_COUNTER_CLOCKWISE;
    pipe_info.multisample_state.sample_count = SDL_GPU_SAMPLECOUNT_1;
    pipe_info.target_info.num_color_targets  = 1;
    pipe_info.target_info.color_target_descriptions = &color_target;
    gpu_pipeline = SDL_CreateGPUGraphicsPipeline(gpu_device, &pipe_info);
    SDL_ReleaseGPUShader(gpu_device, vs);
    SDL_ReleaseGPUShader(gpu_device, fs);
    if (!gpu_pipeline) {
        Sys_Error("SDL_CreateGPUGraphicsPipeline failed: %s", SDL_GetError());
        return 0;
    }

    // Second pipeline: crop-screenshot overlay (rect_overlay shaders) with
    // standard alpha blending so the fragment shader can dim, discard, or
    // draw white border pixels by tweaking output alpha.
    SDL_GPUShaderCreateInfo rvs_info = {0};
    SDL_GPUShaderCreateInfo rfs_info = {0};
    rvs_info.stage = SDL_GPU_SHADERSTAGE_VERTEX;
    rfs_info.stage = SDL_GPU_SHADERSTAGE_FRAGMENT;
    rfs_info.num_uniform_buffers = 1;
    if (active & SDL_GPU_SHADERFORMAT_MSL) {
        rvs_info.code = (const Uint8 *)rect_overlay_vert_msl;
        rvs_info.code_size = strlen(rect_overlay_vert_msl);
        rvs_info.entrypoint = "main0";
        rvs_info.format = SDL_GPU_SHADERFORMAT_MSL;
        rfs_info.code = (const Uint8 *)rect_overlay_frag_msl;
        rfs_info.code_size = strlen(rect_overlay_frag_msl);
        rfs_info.entrypoint = "main0";
        rfs_info.format = SDL_GPU_SHADERFORMAT_MSL;
    } else {
        rvs_info.code = rect_overlay_vert_spv;
        rvs_info.code_size = rect_overlay_vert_spv_size;
        rvs_info.entrypoint = "main";
        rvs_info.format = SDL_GPU_SHADERFORMAT_SPIRV;
        rfs_info.code = rect_overlay_frag_spv;
        rfs_info.code_size = rect_overlay_frag_spv_size;
        rfs_info.entrypoint = "main";
        rfs_info.format = SDL_GPU_SHADERFORMAT_SPIRV;
    }
    SDL_GPUShader *rvs = SDL_CreateGPUShader(gpu_device, &rvs_info);
    SDL_GPUShader *rfs = SDL_CreateGPUShader(gpu_device, &rfs_info);
    if (!rvs || !rfs) {
        Sys_Error("SDL_CreateGPUShader (rect_overlay) failed: %s", SDL_GetError());
        return 0;
    }
    SDL_GPUColorTargetDescription rect_target = {0};
    rect_target.format = gpu_swapchain_format;
    rect_target.blend_state.enable_blend          = true;
    rect_target.blend_state.src_color_blendfactor = SDL_GPU_BLENDFACTOR_SRC_ALPHA;
    rect_target.blend_state.dst_color_blendfactor = SDL_GPU_BLENDFACTOR_ONE_MINUS_SRC_ALPHA;
    rect_target.blend_state.color_blend_op        = SDL_GPU_BLENDOP_ADD;
    rect_target.blend_state.src_alpha_blendfactor = SDL_GPU_BLENDFACTOR_ONE;
    rect_target.blend_state.dst_alpha_blendfactor = SDL_GPU_BLENDFACTOR_ONE_MINUS_SRC_ALPHA;
    rect_target.blend_state.alpha_blend_op        = SDL_GPU_BLENDOP_ADD;
    SDL_GPUGraphicsPipelineCreateInfo rpipe_info = {0};
    rpipe_info.vertex_shader   = rvs;
    rpipe_info.fragment_shader = rfs;
    rpipe_info.primitive_type  = SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
    rpipe_info.rasterizer_state.fill_mode  = SDL_GPU_FILLMODE_FILL;
    rpipe_info.rasterizer_state.cull_mode  = SDL_GPU_CULLMODE_NONE;
    rpipe_info.rasterizer_state.front_face = SDL_GPU_FRONTFACE_COUNTER_CLOCKWISE;
    rpipe_info.multisample_state.sample_count = SDL_GPU_SAMPLECOUNT_1;
    rpipe_info.target_info.num_color_targets  = 1;
    rpipe_info.target_info.color_target_descriptions = &rect_target;
    gpu_rect_pipeline = SDL_CreateGPUGraphicsPipeline(gpu_device, &rpipe_info);
    SDL_ReleaseGPUShader(gpu_device, rvs);
    SDL_ReleaseGPUShader(gpu_device, rfs);
    if (!gpu_rect_pipeline) {
        Sys_Error("SDL_CreateGPUGraphicsPipeline (rect_overlay) failed: %s",
                  SDL_GetError());
        return 0;
    }

    SDL_GPUSamplerCreateInfo samp_info = {0};
    samp_info.min_filter     = SDL_GPU_FILTER_NEAREST;
    samp_info.mag_filter     = SDL_GPU_FILTER_NEAREST;
    samp_info.mipmap_mode    = SDL_GPU_SAMPLERMIPMAPMODE_NEAREST;
    samp_info.address_mode_u = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE;
    samp_info.address_mode_v = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE;
    samp_info.address_mode_w = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE;
    gpu_sampler = SDL_CreateGPUSampler(gpu_device, &samp_info);

    SDL_GPUTextureCreateInfo pal_info = {0};
    pal_info.type                 = SDL_GPU_TEXTURETYPE_2D;
    pal_info.format               = SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM;
    pal_info.usage                = SDL_GPU_TEXTUREUSAGE_SAMPLER;
    pal_info.width                = 256;
    pal_info.height               = VID_NUM_PALETTES;
    pal_info.layer_count_or_depth = 1;
    pal_info.num_levels           = 1;
    pal_info.sample_count         = SDL_GPU_SAMPLECOUNT_1;
    gpu_palette_tex = SDL_CreateGPUTexture(gpu_device, &pal_info);

    SDL_GPUTransferBufferCreateInfo pal_xfer_info = {0};
    pal_xfer_info.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD;
    pal_xfer_info.size  = 256 * VID_NUM_PALETTES * 4;
    gpu_palette_xfer = SDL_CreateGPUTransferBuffer(gpu_device, &pal_xfer_info);

    gpu_create_frame_textures(vid_super_w, vid_super_h);
    return 1;
}

static void gpu_shutdown(void) {
    if (!gpu_device) return;
    if (gpu_pipeline)       SDL_ReleaseGPUGraphicsPipeline(gpu_device, gpu_pipeline);
    if (gpu_rect_pipeline)  SDL_ReleaseGPUGraphicsPipeline(gpu_device, gpu_rect_pipeline);
    if (gpu_sampler)        SDL_ReleaseGPUSampler         (gpu_device, gpu_sampler);
    if (gpu_fb_tex)         SDL_ReleaseGPUTexture         (gpu_device, gpu_fb_tex);
    if (gpu_palette_id_tex) SDL_ReleaseGPUTexture         (gpu_device, gpu_palette_id_tex);
    if (gpu_palette_tex)    SDL_ReleaseGPUTexture         (gpu_device, gpu_palette_tex);
    if (gpu_frame_xfer)     SDL_ReleaseGPUTransferBuffer  (gpu_device, gpu_frame_xfer);
    if (gpu_palette_xfer)   SDL_ReleaseGPUTransferBuffer  (gpu_device, gpu_palette_xfer);
    SDL_ReleaseWindowFromGPUDevice(gpu_device, sdl_window);
    SDL_DestroyGPUDevice(gpu_device);
    gpu_device = NULL; gpu_pipeline = NULL; gpu_rect_pipeline = NULL;
    gpu_sampler = NULL;
    gpu_fb_tex = NULL; gpu_palette_id_tex = NULL; gpu_palette_tex = NULL;
    gpu_frame_xfer = NULL; gpu_palette_xfer = NULL;
}

// Forward decls — implemented in imgui_layer.c via imgui_bridge.cpp.
extern void ImguiLayer_PrepareGPU(SDL_GPUCommandBuffer *cmd);
extern void ImguiLayer_RenderGPU (SDL_GPUCommandBuffer *cmd, SDL_GPURenderPass *pass);
extern int Editor_IsOpen(void);
extern int ImguiLayer_IsOpen(void);

static void gpu_render_frame(void) {
    // GPU texture is sized to the *super* buffer dims (the actual extent the
    // software renderer fills). With ss=1 these equal vid_render_w/h; with
    // ss>1 they are larger and palette.frag.glsl averages each ss×ss block of
    // expanded texels down to the render grid (true SSAA — the sampler is
    // NEAREST and the R8_UINT index texture can't be hardware-filtered).
    int tex_w = vid_super_w;
    int tex_h = vid_super_h;
    if (tex_w != gpu_fb_tex_w || tex_h != gpu_fb_tex_h)
        gpu_create_frame_textures(tex_w, tex_h);

    SDL_GPUCommandBuffer *cmd = SDL_AcquireGPUCommandBuffer(gpu_device);
    if (!cmd) return;

    gpu_upload_palette(cmd);

    Perf_PushScope("gpu_upload");
    void *mapped = SDL_MapGPUTransferBuffer(gpu_device, gpu_frame_xfer, true);
    if (mapped) {
        uint8_t *dst = (uint8_t *)mapped;
        int src_stride = (int)vid.rowbytes;   // = vid_super_w
        for (int y = 0; y < tex_h; y++)
            memcpy(dst + y * tex_w, vid.buffer + y * src_stride, tex_w);
        uint8_t *dst_pid = dst + tex_w * tex_h;
        for (int y = 0; y < tex_h; y++)
            memcpy(dst_pid + y * tex_w, vid_palette_id + y * src_stride, tex_w);
        SDL_UnmapGPUTransferBuffer(gpu_device, gpu_frame_xfer);
    }
    SDL_GPUCopyPass *copy = SDL_BeginGPUCopyPass(cmd);
    {
        SDL_GPUTextureTransferInfo src = {0};
        src.transfer_buffer = gpu_frame_xfer;
        src.pixels_per_row  = (Uint32)tex_w;
        src.rows_per_layer  = (Uint32)tex_h;
        SDL_GPUTextureRegion dst = {0};
        dst.texture = gpu_fb_tex;
        dst.w = (Uint32)tex_w; dst.h = (Uint32)tex_h; dst.d = 1;
        SDL_UploadToGPUTexture(copy, &src, &dst, true);
    }
    {
        SDL_GPUTextureTransferInfo src = {0};
        src.transfer_buffer = gpu_frame_xfer;
        src.offset          = (Uint32)(tex_w * tex_h);
        src.pixels_per_row  = (Uint32)tex_w;
        src.rows_per_layer  = (Uint32)tex_h;
        SDL_GPUTextureRegion dst = {0};
        dst.texture = gpu_palette_id_tex;
        dst.w = (Uint32)tex_w; dst.h = (Uint32)tex_h; dst.d = 1;
        SDL_UploadToGPUTexture(copy, &src, &dst, true);
    }
    SDL_EndGPUCopyPass(copy);
    Perf_PopScope();

    // Scene goes into the editor's Viewport panel whenever the docked overlay
    // is up — the in-game editor OR the F3 dev overlay.
    int scene_in_panel = Editor_IsOpen() || ImguiLayer_IsOpen();
    if (scene_in_panel) {
        gpu_ensure_scene_tex(vid_render_w, vid_render_h);
        SDL_GPUColorTargetInfo sct = {0};
        sct.texture  = gpu_scene_tex;
        sct.load_op  = SDL_GPU_LOADOP_CLEAR;
        sct.store_op = SDL_GPU_STOREOP_STORE;
        sct.clear_color.a = 1.0f;
        SDL_GPURenderPass *spass = SDL_BeginGPURenderPass(cmd, &sct, 1, NULL);
        SDL_BindGPUGraphicsPipeline(spass, gpu_pipeline);
        SDL_GPUViewport svp = {0};
        svp.w = (float)vid_render_w; svp.h = (float)vid_render_h; svp.max_depth = 1.0f;
        SDL_SetGPUViewport(spass, &svp);
        SDL_GPUTextureSamplerBinding sb[3];
        sb[0].texture = gpu_fb_tex;         sb[0].sampler = gpu_sampler;
        sb[1].texture = gpu_palette_id_tex; sb[1].sampler = gpu_sampler;
        sb[2].texture = gpu_palette_tex;    sb[2].sampler = gpu_sampler;
        SDL_BindGPUFragmentSamplers(spass, 0, sb, 3);
        struct { float intensity, size, supersample, pad1; } sp =
            { 0.0f, 1.0f, (float)vid_supersample_active, 0.0f };   // no scanlines in the editor
        SDL_PushGPUFragmentUniformData(cmd, 0, &sp, sizeof(sp));
        SDL_DrawGPUPrimitives(spass, 3, 1, 0, 0);
        SDL_EndGPURenderPass(spass);
    }

    ImguiLayer_PrepareGPU(cmd);

    Perf_PushScope("gpu_present");
    SDL_GPUTexture *swap_tex = NULL;
    Uint32 swap_w = 0, swap_h = 0;
    if (!SDL_WaitAndAcquireGPUSwapchainTexture(cmd, sdl_window, &swap_tex, &swap_w, &swap_h)
        || !swap_tex)
    {
        SDL_SubmitGPUCommandBuffer(cmd);
        Perf_PopScope();
        return;
    }
    {
        static int diag_printed = 0;
        if (!diag_printed) {
            diag_printed = 1;
            int win_w = 0, win_h = 0;
            SDL_GetWindowSize(sdl_window, &win_w, &win_h);
            int px_w = 0, px_h = 0;
            SDL_GetWindowSizeInPixels(sdl_window, &px_w, &px_h);
            Con_Printf("vid: render=%dx%d super=%dx%d ss=%d vid.w=%u vid.h=%u rowbytes=%u\n",
                       vid_render_w, vid_render_h, vid_super_w, vid_super_h,
                       vid_supersample_active, vid.width, vid.height, vid.rowbytes);
            Con_Printf("vid: swap=%ux%u win=%dx%d px=%dx%d\n",
                       swap_w, swap_h, win_w, win_h, px_w, px_h);
        }
    }

    SDL_GPUColorTargetInfo color_target = {0};
    color_target.texture = swap_tex;
    color_target.load_op = SDL_GPU_LOADOP_CLEAR;
    color_target.store_op = SDL_GPU_STOREOP_STORE;
    // clear_color default-zeroes to opaque-black, which is what we want.
    color_target.clear_color.a = 1.0f;
    SDL_GPURenderPass *pass = SDL_BeginGPURenderPass(cmd, &color_target, 1, NULL);

    if (!scene_in_panel) {
        SDL_BindGPUGraphicsPipeline(pass, gpu_pipeline);

        // Integer-scale aspect-preserving letterbox. Matches the prior
        // SDL_RenderLogicalPresentation INTEGER_SCALE behaviour.
        int int_scale = (int)(swap_w / (Uint32)vid_render_w);
        int sy        = (int)(swap_h / (Uint32)vid_render_h);
        if (sy < int_scale) int_scale = sy;
        if (int_scale < 1)  int_scale = 1;
        int vp_w = vid_render_w * int_scale;
        int vp_h = vid_render_h * int_scale;
        SDL_GPUViewport vp = {0};
        vp.x = (float)(((int)swap_w - vp_w) / 2);
        vp.y = (float)(((int)swap_h - vp_h) / 2);
        vp.w = (float)vp_w;
        vp.h = (float)vp_h;
        vp.max_depth = 1.0f;
        SDL_SetGPUViewport(pass, &vp);

        SDL_GPUTextureSamplerBinding bindings[3];
        bindings[0].texture = gpu_fb_tex;         bindings[0].sampler = gpu_sampler;
        bindings[1].texture = gpu_palette_id_tex; bindings[1].sampler = gpu_sampler;
        bindings[2].texture = gpu_palette_tex;    bindings[2].sampler = gpu_sampler;
        SDL_BindGPUFragmentSamplers(pass, 0, bindings, 3);

        // Fragment params: scanline overlay + supersample factor. Layout matches
        // the std140 UBO in palette.frag.glsl (four floats = 16 bytes). The shader
        // averages each ss×ss block of expanded texels down to one render texel, so
        // it needs the live ss to know the block size (ss=1 → single fetch).
        struct { float intensity, size, supersample, pad1; } scan_params;
        float intensity = vid_scanline_intensity.value;
        float size      = vid_scanline_size.value;
        if (vid_scanlines.value == 0.0f) intensity = 0.0f;
        if (intensity < 0.0f) intensity = 0.0f;
        if (intensity > 1.0f) intensity = 1.0f;
        if (size < 1.0f) size = 1.0f;
        if (size > 8.0f) size = 8.0f;
        scan_params.intensity   = intensity;
        scan_params.size        = size;
        scan_params.supersample = (float)vid_supersample_active;
        scan_params.pad1        = 0.0f;
        SDL_PushGPUFragmentUniformData(cmd, 0, &scan_params, sizeof(scan_params));

        SDL_DrawGPUPrimitives(pass, 3, 1, 0, 0);

        // Crop-screenshot selection overlay: draws after the palette pass and
        // before ImGui, so it overlays the framebuffer but the dev overlay still
        // sits on top.
        if (Crop_Active()) {
            int x0 = 0, y0 = 0, x1 = 0, y1 = 0;
            Crop_GetRect(&x0, &y0, &x1, &y1);
            // Rect is in super-pixel space; map super → viewport-local swapchain
            // pixels. The palette pass already scaled (vid_super_w × vid_super_h)
            // into (vp_w × vp_h), so use that ratio.
            float sx = (float)vp_w / (float)vid_super_w;
            float sy = (float)vp_h / (float)vid_super_h;
            struct {
                float rect[4];      // x0, y0, x1_excl, y1_excl
                float viewport[4];  // origin_x, origin_y, w, h (swap-pixels)
                float border_w;
                float dim_alpha;
                float pad0, pad1;
            } rp;
            rp.rect[0] = (float)x0       * sx;
            rp.rect[1] = (float)y0       * sy;
            rp.rect[2] = (float)(x1 + 1) * sx;
            rp.rect[3] = (float)(y1 + 1) * sy;
            rp.viewport[0] = vp.x;
            rp.viewport[1] = vp.y;
            rp.viewport[2] = vp.w;
            rp.viewport[3] = vp.h;
            rp.border_w  = (float)int_scale;  // one logical pixel
            rp.dim_alpha = 0.5f;
            rp.pad0 = rp.pad1 = 0.0f;
            SDL_BindGPUGraphicsPipeline(pass, gpu_rect_pipeline);
            SDL_PushGPUFragmentUniformData(cmd, 0, &rp, sizeof(rp));
            SDL_DrawGPUPrimitives(pass, 3, 1, 0, 0);
        }
    }

    ImguiLayer_RenderGPU(cmd, pass);

    SDL_EndGPURenderPass(pass);

    // Optional GPU screenshot: schedule a download from the swapchain texture
    // before submit, so the fence we acquire is post-rasterise. Then map the
    // readback transfer buffer and encode PNG.
    int do_shot = gpu_screenshot_pending;
    if (do_shot) {
        int rb_bytes = (int)swap_w * (int)swap_h * 4;
        if (!gpu_readback_xfer || gpu_readback_size < rb_bytes) {
            if (gpu_readback_xfer) SDL_ReleaseGPUTransferBuffer(gpu_device, gpu_readback_xfer);
            SDL_GPUTransferBufferCreateInfo rb_info = {0};
            rb_info.usage = SDL_GPU_TRANSFERBUFFERUSAGE_DOWNLOAD;
            rb_info.size  = (Uint32)rb_bytes;
            gpu_readback_xfer = SDL_CreateGPUTransferBuffer(gpu_device, &rb_info);
            gpu_readback_size = rb_bytes;
        }
        if (gpu_readback_xfer) {
            SDL_GPUCopyPass *cp = SDL_BeginGPUCopyPass(cmd);
            SDL_GPUTextureRegion src = {0};
            src.texture = swap_tex;
            src.w = swap_w; src.h = swap_h; src.d = 1;
            SDL_GPUTextureTransferInfo dst = {0};
            dst.transfer_buffer = gpu_readback_xfer;
            dst.pixels_per_row  = swap_w;
            dst.rows_per_layer  = swap_h;
            SDL_DownloadFromGPUTexture(cp, &src, &dst);
            SDL_EndGPUCopyPass(cp);
        }
    }

    if (do_shot && gpu_readback_xfer) {
        SDL_GPUFence *fence = SDL_SubmitGPUCommandBufferAndAcquireFence(cmd);
        if (fence) {
            SDL_WaitForGPUFences(gpu_device, true, &fence, 1);
            void *mapped = SDL_MapGPUTransferBuffer(gpu_device, gpu_readback_xfer, false);
            if (mapped) {
                // Swapchain on macOS is B8G8R8A8_UNORM; swizzle to RGB for PNG.
                // (Other backends may use different orders — extend if needed.)
                int W = (int)swap_w, H = (int)swap_h;
                unsigned char *rgb = (unsigned char *)malloc((size_t)W * H * 3);
                if (rgb) {
                    const uint8_t *src = (const uint8_t *)mapped;
                    for (int i = 0; i < W * H; i++) {
                        rgb[i*3 + 0] = src[i*4 + 2]; // R from B-position
                        rgb[i*3 + 1] = src[i*4 + 1]; // G
                        rgb[i*3 + 2] = src[i*4 + 0]; // B from R-position
                    }
                    stbi_write_png(gpu_screenshot_path, W, H, 3, rgb, W * 3);
                    free(rgb);
                }
                SDL_UnmapGPUTransferBuffer(gpu_device, gpu_readback_xfer);
            }
            SDL_ReleaseGPUFence(gpu_device, fence);
        }
        gpu_screenshot_pending = 0;
    } else {
        SDL_SubmitGPUCommandBuffer(cmd);
    }
    Perf_PopScope();
}

// Request a GPU-side screenshot. Returns 1 if the request was queued (i.e.
// no other screenshot is pending). The next gpu_render_frame downloads the
// swapchain texture and writes a PNG to `path`. Caller-supplied path must be
// short enough to fit in gpu_screenshot_path (~500 bytes).
int VID_RequestGPUScreenshot(const char *path) {
    if (!gpu_device)        return 0;
    if (gpu_screenshot_pending) return 0;
    if (!path || !path[0])  return 0;
    snprintf(gpu_screenshot_path, sizeof(gpu_screenshot_path), "%s", path);
    gpu_screenshot_pending = 1;
    return 1;
}
int VID_GPUScreenshotPending(void) { return gpu_screenshot_pending; }

static void VID_ApplyResolution(int render_scale, int ss)
{
    extern short *d_pzbuffer;
    extern int    D_SurfaceCacheForRes(int w, int h);
    extern void   D_InitCaches(void *buffer, int size);

    if (render_scale < 1) render_scale = 1;
    if (render_scale > 4) render_scale = 4;
    if (ss < 1) ss = 1;
    if (ss > 4) ss = 4;
    while (render_scale * ss > 8 && ss > 1) ss--;

    int render_w = VID_WIDTH  * render_scale;
    int render_h = VID_HEIGHT * render_scale;
    int super_w  = render_w * ss;
    int super_h  = render_h * ss;

    if (gpu_device) {
        gpu_create_frame_textures(render_w, render_h);
    }

    vid_render_w = render_w;
    vid_render_h = render_h;
    vid_super_w  = super_w;
    vid_super_h  = super_h;
    vid_scale_active       = render_scale;
    vid_supersample_active = ss;

    vid.width         = super_w;
    vid.height        = super_h;
    vid.rowbytes      = super_w;
    vid.conwidth      = super_w;
    vid.conheight     = super_h;
    vid.conrowbytes   = super_w;
    vid.maxwarpwidth  = WARP_WIDTH;
    vid.maxwarpheight = WARP_HEIGHT;
    vid.recalc_refdef = 1;

    {
        extern void D_FlushCaches(void);
        D_FlushCaches();
    }
    int zbuf_bytes  = super_w * super_h * sizeof(short);
    int cache_bytes = D_SurfaceCacheForRes(super_w, super_h);
    D_InitCaches((byte *)d_pzbuffer + zbuf_bytes, cache_bytes);
}

static void VID_ApplyWindowScale(int scale)
{
    SDL_SetWindowSize(sdl_window, VID_WIDTH * scale, VID_HEIGHT * scale);
}

// Capture the current SDL window position AND size into the archived cvars
// so the next launch can restore it. Invoked from the Video Options menu —
// no autosave, so casual dragging won't quietly overwrite saved values.
static void VID_SaveWindow(void)
{
    int x = 0, y = 0, w = 0, h = 0;
    if (!sdl_window) return;
    SDL_GetWindowPosition(sdl_window, &x, &y);
    SDL_GetWindowSize(sdl_window, &w, &h);
    Cvar_SetValue("vid_window_x", (float)x);
    Cvar_SetValue("vid_window_y", (float)y);
    Cvar_SetValue("vid_window_w", (float)w);
    Cvar_SetValue("vid_window_h", (float)h);
}

