// Map a mouse-event window pixel coord into framebuffer / logical coords.
// Matches the integer-scale letterbox the GPU present uses: window (wx,wy)
// outside the viewport returns the nearest clamped logical pixel. The crop
// screenshot tool uses this to translate drag endpoints into vid.buffer-
// space rectangles.
void VID_WindowToLogical(float wx, float wy, float *lx, float *ly)
{
    int win_w = 0, win_h = 0;
    if (sdl_window) SDL_GetWindowSize(sdl_window, &win_w, &win_h);
    if (win_w <= 0 || win_h <= 0 || vid_render_w <= 0 || vid_render_h <= 0) {
        if (lx) *lx = wx;
        if (ly) *ly = wy;
        return;
    }
    // Integer-scale aspect-preserving letterbox, identical to gpu_render_frame.
    int sx = win_w / vid_render_w;
    int sy = win_h / vid_render_h;
    int int_scale = sx < sy ? sx : sy;
    if (int_scale < 1) int_scale = 1;
    int vp_w = vid_render_w * int_scale;
    int vp_h = vid_render_h * int_scale;
    float vp_x = (float)((win_w - vp_w) / 2);
    float vp_y = (float)((win_h - vp_h) / 2);
    if (lx) *lx = (wx - vp_x) / (float)int_scale;
    if (ly) *ly = (wy - vp_y) / (float)int_scale;
}

